const REGIONS = [
  'Королевский тракт (у каменного путевого столба)',
  'Тропа сквозь Шепчущий лес (у развилки старых сосен)',
  'Горный перевал Ветров (в укрытии от бури у скалы)',
  'Заброшенный постоялый двор «Семь Колоколов»',
  'Песчаный брод через бурную реку',
  'Окраина торгового тракта у моста Троллей'
];

export function generateTravelingMerchant(options: TravelingMerchantOptions = {}): { text: string; raw: TravelingMerchantRawData } {
  const archetypeKeys = Object.keys(ARCHETYPES);
  let archKey = options.archetype && ARCHETYPES[options.archetype] ? options.archetype : randomChoice(archetypeKeys);
  if (archKey === 'random') archKey = randomChoice(archetypeKeys);

  const arch = ARCHETYPES[archKey];
  const name = randomChoice(arch.names);
  
  // Custom Race or random from archetype
  const RACES_MAP: Record<string, string> = {
    human: 'Человек',
    elf: 'Эльф',
    dwarf: 'Дварф',
    halfling: 'Полурослик',
    gnome: 'Гном',
    orc: 'Полуорк',
    exotic: 'Драконорожденный / Тифлинг'
  };
  const race = options.race && options.race !== 'random' && RACES_MAP[options.race]
    ? RACES_MAP[options.race]
    : randomChoice(arch.races);

  // Custom Attitude/Personality
  const ATTITUDE_MAP: Record<string, string> = {
    friendly: 'Доброжелательный путник, напевает баллады и легко дающий скидку 10% за хорошую беседу.',
    greedy: 'Жадный и расчетливый торгаш, скрупулезно завышающий цены на 20% для незнакомцев.',
    suspicious: 'Подозрительный и осторожный, держит руку на кошельке и осматривает гостей с ног до головы.',
    secretive: 'Таинственный молчун, предпочитает разговаривать знаками и тихим полушепотом.'
  };
  const personality = options.attitude && options.attitude !== 'random' && ATTITUDE_MAP[options.attitude]
    ? ATTITUDE_MAP[options.attitude]
    : randomChoice(arch.personalities);

  const transport = randomChoice(arch.transports);
  const tradeQuirk = randomChoice(arch.quirks);
  const roadRumor = randomChoice(arch.rumors);
  const meetingPlace = options.region && options.region !== 'random' ? options.region : randomChoice(REGIONS);

  // Cash in purse based on priceTier
  let purseMinGp = 15;
  let purseMaxGp = 65;
  if (options.priceTier === 'poor') { purseMinGp = 5; purseMaxGp = 20; }
  else if (options.priceTier === 'wealthy') { purseMinGp = 100; purseMaxGp = 350; }

  const purseGp = randomInt(purseMinGp, purseMaxGp);
  const purseSp = randomInt(8, 40);
  const purse = `${purseGp} gp, ${purseSp} sp (наличные для размена и скупки)`;

  // Select item count
  let countToPick = randomInt(3, 5);
  if (options.itemCount === 'small') countToPick = randomInt(2, 3);
  else if (options.itemCount === 'medium') countToPick = randomInt(4, 5);
  else if (options.itemCount === 'large') countToPick = randomInt(6, 8);

  const shuffledPool = [...arch.itemPool].sort(() => Math.random() - 0.5);
  const inventory = shuffledPool.slice(0, Math.min(countToPick, shuffledPool.length));

  const raw: TravelingMerchantRawData = {
    name,
    title: arch.title,
    archetype: archKey,
    race,
    personality,
    transport,
    purse,
    meetingPlace,
    roadRumor,
    tradeQuirk,
    inventory
  };

  const text = `
╔══════════════════════════════════════════════════════════════════════╗
  СТРАНСТВУЮЩИЙ ТОРГОВЕЦ: ${name.toUpperCase()} (${race.toUpperCase()})
  Род занятий: ${arch.title}
  Место встречи: ${meetingPlace}
╠══════════════════════════════════════════════════════════════════════╣
  ТРАНСПОРТ И ВЬЮЧНОЕ ЖИВОТНОЕ:
  ✦ ${transport}

  ХАРАКТЕР И ПОВЕДЕНИЕ:
  ✦ ${personality}

  ОСОБЕННОСТИ ТОРГОВЛИ И СКИДКИ:
  ✦ ${tradeQuirk}

  НАЛИЧНЫЙ КОШЕЛЕК ДЛЯ РАЗМЕНА:
  ✦ ${purse}
╠──────────────────────────────────────────────────────────────────────╢
  АССОРТИМЕНТ С ДОРОГИ (НЕБОЛЬШОЙ ВЫБОР: ${inventory.length} ПРЕДМ.):
${inventory.map((it, idx) => `  ${idx + 1}. ${it.name} — [${it.price}]\n     Категория: ${it.category} | ${it.desc}`).join('\n\n')}
╠──────────────────────────────────────────────────────────────────────╢
  СВЕЖИЕ СЛУХИ С ТРАКТА:
  ✦ "${roadRumor}"
╚══════════════════════════════════════════════════════════════════════╝
`.trim();

  return { text, raw };
}
