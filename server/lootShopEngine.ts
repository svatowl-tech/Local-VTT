export function generateLoot(optionsOrType: LootOptions | string = {}): { text: string; raw: any } {
  let options: LootOptions = {};
  if (typeof optionsOrType === 'string') {
    options = { type: optionsOrType };
  } else {
    options = optionsOrType;
  }

  const sourceKey = options.type && LOOT_SOURCES[options.type] ? options.type : 'humanoid';
  const source = LOOT_SOURCES[sourceKey];

  const tier = options.tier || 'low';
  const richness = options.richness || 'standard';
  const condKey = options.condition && CONDITIONS_DATA[options.condition] ? options.condition : 'any';
  const condition = CONDITIONS_DATA[condKey];

  // Base coin scale by tier
  let coinMultiplier = 1;
  if (tier === 'medium') coinMultiplier = 4;
  if (tier === 'high') coinMultiplier = 12;
  if (tier === 'epic') coinMultiplier = 35;

  if (richness === 'poor') coinMultiplier *= 0.4;
  if (richness === 'rich') coinMultiplier *= 2.2;
  if (richness === 'lavish') coinMultiplier *= 4.5;

  const cp = Math.round(randomInt(5, 40) * coinMultiplier);
  const sp = Math.round(randomInt(2, 25) * coinMultiplier);
  const gp = Math.round(randomInt(1, 10) * coinMultiplier);

  // Pick items
  const pickedItems: string[] = [];
  const itemCount = richness === 'poor' ? 1 : (richness === 'lavish' ? randomInt(3, 5) : randomInt(2, 3));
  for (let i = 0; i < itemCount; i++) {
    pickedItems.push(randomChoice(source.itemPool));
  }

  // Valuable curiosity
  let valuable: string | null = null;
  if (richness !== 'poor' && Math.random() < (richness === 'lavish' ? 0.95 : 0.65)) {
    valuable = randomChoice(source.valuablesPool);
  }

  const trinket = randomChoice(TRINKETS);
  const clue = randomChoice(source.documentOrClue);

  const rawData = {
    source: source.name,
    category: source.category,
    tier,
    richness,
    condition: condition.name,
    conditionDesc: condition.desc,
    coins: { cp, sp, gp },
    items: pickedItems,
    valuable,
    trinket,
    clue
  };

  const text = `
╔══════════════════════════════════════════════════════════════════════╗
  НАЙДЕННЫЙ ЛУТ И ДОБЫЧА: ${source.name.toUpperCase()}
  Категория: ${source.category} | Уровень опасности: ${tier.toUpperCase()}
  Состояние: ${condition.name} (${condition.desc})
╠══════════════════════════════════════════════════════════════════════╣
  МОНЕТЫ И НАЛИЧНОСТЬ:
  • Медные (cp):   ${cp > 0 ? cp.toLocaleString('ru-RU') : '0'}
  • Серебряные (sp): ${sp > 0 ? sp.toLocaleString('ru-RU') : '0'}
  • Золотые (gp):    ${gp > 0 ? gp.toLocaleString('ru-RU') : '0'}
╠──────────────────────────────────────────────────────────────────────╢
  НАЙДЕННЫЕ ВЕЩИ И ТРОФЕИ:
${pickedItems.map(it => `  • ${it}`).join('\n')}
${valuable ? `\n  ЮВЕЛИРНАЯ ДИКОВИНКА / ЦЕННОСТЬ:\n  ✦ ${valuable}` : ''}
╠──────────────────────────────────────────────────────────────────────╢
  ДИКОВИНКА / БЕЗДЕЛУШКА (TRINKET):
  ✦ ${trinket}
╠──────────────────────────────────────────────────────────────────────╢
  СЮЖЕТНАЯ УЛИКА / ДОКУМЕНТ:
  ✦ ${clue}
╚══════════════════════════════════════════════════════════════════════╝
`.trim();

  return { text, raw: rawData };
}

