/**
 * High-Performance Server-Side Loot, Shop, Merchant & Magic Items Engine
 * Generates rich pocket loot, creature harvest trophies, dungeon chest stashes, alchemical finds,
 * battlefield scavenges, and shipwreck salvage by danger tier and richness.
 */

function randomChoice<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

function randomInt(min: number, max: number): number {
  return Math.floor(Math.random() * (max - min + 1)) + min;
}

